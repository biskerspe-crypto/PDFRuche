/**
 * Check if a tool is a V2 (Atelier) version.
 * V2 tools carry the `-v2` suffix in id/slug and the `atelier-v2` feature.
 */
export function isV2Tool(tool: { slug: string }): boolean {
  return tool.slug.endsWith('-v2');
}

/**
 * Get tools visible in listings/cards (V2 only).
 * Old-version cards are hidden; V1 routes remain accessible directly.
 */
export function getDisplayTools(): Tool[] {
  return tools.filter((tool) => !tool.disabled && isV2Tool(tool));
}

/**
 * Get visible (V2) tools by category.
 */
export function getDisplayToolsByCategory(category: ToolCategory): Tool[] {
  return tools.filter((tool) => tool.category === category && !tool.disabled && isV2Tool(tool));
}

/**
 * Map a tool id/slug to its V2 counterpart when it exists.
 * Used for favorites migration and related-tools links.
 */
export function toV2Id(id: string): string {
  const v2 = `${id}-v2`;
  return tools.some((tool) => tool.id === v2 && !tool.disabled) ? v2 : id;
}

/**
 * Get all tools (excluding disabled tools)
 */
export function getAllTools(): Tool[] {
  return tools.filter(tool => !tool.disabled);
}

/**
 * Get all tools including disabled ones (for admin)
 */
export function getAllToolsIncludingDisabled(): Tool[] {
  return tools;
}

/**
 * Get tool by ID
 */
export function getToolById(id: string): Tool | undefined {
  return tools.find((tool) => tool.id === id && !tool.disabled);
}

/**
 * Get tool by slug
 */
export function getToolBySlug(slug: string): Tool | undefined {
  return tools.find((tool) => tool.slug === slug && !tool.disabled);
}

/**
 * Get tools by category (excluding disabled tools)
 */
export function getToolsByCategory(category: ToolCategory): Tool[] {
  return tools.filter((tool) => tool.category === category && !tool.disabled);
}

/**
 * Get all tool IDs
 */
export function getAllToolIds(): string[] {
  return tools.map((tool) => tool.id);
}

/**
 * Check if a tool ID exists
 */
export function toolExists(id: string): boolean {
  return tools.some((tool) => tool.id === id);
}

